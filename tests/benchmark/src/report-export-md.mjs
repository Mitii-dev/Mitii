import {
  enrichReportEnvironment,
  fmtDuration,
  fmtPct,
  fmtTokens,
  shortDesc,
} from './report-format.mjs';

/**
 * Elegant, shareable Markdown brief for LinkedIn / GitHub / blogs.
 */
export function renderExportMarkdown(report, options = {}) {
  const data = enrichReportEnvironment(report, options);
  const env = data.environment ?? {};
  const overall = data.overall ?? {};
  const usage = data.usageTotals ?? {};
  const difficulties = data.difficulties ?? {};
  const results = Array.isArray(data.results) ? data.results : [];
  const failed = results.filter((r) => !r.passed);
  const ordered = results
    .slice()
    .sort((a, b) => Number(a.passed) - Number(b.passed));

  const signal = data.signal || '—';
  const suite = data.suite || 'all';
  const runId = options.runId || data.runId || 'run';

  const lines = [];
  lines.push(`# Mitii · Agent Evaluation Brief`);
  lines.push('');
  lines.push(`> **${signal}** · \`${suite}\` · Family score **${fmtPct(overall.familyScore)}**`);
  lines.push('');
  lines.push(`---`);
  lines.push('');
  lines.push(`## Setup`);
  lines.push('');
  lines.push(`| | |`);
  lines.push(`|---|---|`);
  lines.push(`| **Model** | \`${escapeCell(env.model || 'unknown')}\` |`);
  lines.push(
    `| **Context window** | ${escapeCell(env.contextWindowLabel || '—')} |`,
  );
  lines.push(`| **Provider** | \`${escapeCell(env.provider || 'unknown')}\` |`);
  if (env.baseUrl) {
    lines.push(`| **Endpoint** | \`${escapeCell(env.baseUrl)}\` |`);
  }
  lines.push(`| **Run** | \`${escapeCell(runId)}\` |`);
  lines.push(
    `| **When** | ${escapeCell(fmtRange(data.startedAt, data.finishedAt))} |`,
  );
  lines.push(
    `| **Cases** | ${overall.passed ?? 0}/${overall.total ?? results.length} passed · ${overall.failed ?? failed.length} failed |`,
  );
  lines.push(
    `| **Tokens** | in ${fmtTokens(usage.inputTokens)} · out ${fmtTokens(usage.outputTokens)} |`,
  );
  lines.push(`| **Avg duration** | ${fmtDuration(overall.avgDurationMs)} |`);
  lines.push('');
  lines.push(`## Scorecard`);
  lines.push('');
  lines.push(`| Difficulty | Passed | Family score | Gate |`);
  lines.push(`|---|---:|---:|:---:|`);
  for (const d of ['easy', 'medium', 'hard']) {
    const item = difficulties[d];
    if (!item?.total) continue;
    const gate =
      data.gateResults?.[d] === null || data.gateResults?.[d] === undefined
        ? '—'
        : data.gateResults[d]
          ? 'PASS'
          : 'FAIL';
    lines.push(
      `| ${d} | ${item.passed}/${item.total} | ${fmtPct(item.familyScore)} | ${gate} |`,
    );
  }
  lines.push('');
  lines.push(`## Cases`);
  lines.push('');
  lines.push(
    failed.length
      ? `_Failures listed first (${failed.length})._`
      : `_All cases passed._`,
  );
  lines.push('');
  lines.push(`| Status | Test case | Category | Time | In | Out |`);
  lines.push(`|:---:|---|---|---:|---:|---:|`);
  for (const r of ordered) {
    const u = r.usage ?? {};
    const title = `\`${escapeCell(r.id)}\`<br>${escapeCell(shortDesc(r.prompt, 88))}`;
    lines.push(
      `| ${r.passed ? 'PASS' : '**FAIL**'} | ${title} | ${escapeCell(r.category || '—')} | ${fmtDuration(r.durationMs)} | ${fmtTokens(u.inputTokens)} | ${fmtTokens(u.outputTokens)} |`,
    );
  }

  if (failed.length) {
    lines.push('');
    lines.push(`## Failed cases`);
    lines.push('');
    for (const r of failed) {
      const u = r.usage ?? {};
      lines.push(`### \`${r.id}\``);
      lines.push('');
      lines.push(`- **Category:** ${r.category || '—'} · **Difficulty:** ${r.difficulty || '—'}`);
      lines.push(
        `- **Time:** ${fmtDuration(r.durationMs)} · **Tokens:** in ${fmtTokens(u.inputTokens)} / out ${fmtTokens(u.outputTokens)}`,
      );
      lines.push(`- **Prompt:** ${escapeCell(shortDesc(r.prompt, 160))}`);
      if (r.error) lines.push(`- **Error:** ${escapeCell(r.error)}`);
      lines.push('');
    }
  }

  lines.push(`---`);
  lines.push('');
  lines.push(
    `_Generated by [Mitii](https://github.com) agent benchmark · Model \`${escapeCell(env.model || 'unknown')}\` · ${escapeCell(env.contextWindowLabel || 'context n/a')}_`,
  );
  lines.push('');
  return lines.join('\n');
}

function fmtRange(start, end) {
  const a = fmtStamp(start);
  const b = fmtStamp(end);
  if (a === '—' && b === '—') return '—';
  return `${a} → ${b}`;
}

function fmtStamp(iso) {
  if (!iso) return '—';
  try {
    return new Date(iso).toISOString().replace('T', ' ').replace(/\.\d+Z$/, ' UTC');
  } catch {
    return String(iso);
  }
}

function escapeCell(value) {
  return String(value ?? '')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ')
    .trim();
}
